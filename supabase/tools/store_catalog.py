#!/usr/bin/env python3
"""Prints the server's store catalogue as SQL, read from the game's content files.

The server rolls boxes, prices goods and pays pass rewards from these tables, so they must
match the app. When a content file changes, run this and put its output in a new migration
(`python3 supabase/tools/store_catalog.py > supabase/migrations/00NN_store_catalog.sql`).
The engine test ServerCatalogTests fails while the newest catalogue differs from the content.
"""
import json
import os
import sys
from datetime import date, timedelta

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CONTENT = os.path.join(ROOT, "native/Engine/Sources/Simulation/Resources/Content")
APP_CONTENT = os.path.join(ROOT, "native/App/Ledger/Resources/Content")


def load(*parts):
    with open(os.path.join(*parts)) as f:
        return json.load(f)


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def rows(table, cols, values):
    if not values:
        return ""
    out = [f"insert into private.{table} ({', '.join(cols)}) values"]
    out.append(",\n".join("  (" + ", ".join(q(v) for v in r) + ")" for r in values) + ";")
    return "\n".join(out) + "\n"


def main():
    prices = load(CONTENT, "pricing/prices.json")
    boxes = load(CONTENT, "boxes/boxes.json")["boxes"]
    events = load(CONTENT, "boxes/events.json")
    arts = load(CONTENT, "artifacts/artifacts.json")
    cards = load(CONTENT, "cards/cards.json")
    cos = load(CONTENT, "cosmetics/gold_cosmetics.json")
    retired = load(CONTENT, "cosmetics/retired.json")["refunds"]
    levels = load(CONTENT, "progression/level_rewards.json")["rewards"]
    avatars = load(APP_CONTENT, "avatars/avatars.json")["avatars"]
    gold = prices["gold"]
    real = prices["realMoney"]

    seasons = []
    n = 1
    while os.path.exists(os.path.join(CONTENT, f"season/season_{n}.json")):
        seasons.append(load(CONTENT, f"season/season_{n}.json"))
        n += 1
    months = 6
    season_days = months * 365 // 12
    first = date.fromisoformat(seasons[0]["starts"])

    out = ["-- store catalog begin (generated by supabase/tools/store_catalog.py; do not edit by hand)"]
    out.append("truncate private.store_box_kinds, private.store_box_rows, private.store_box_bundles, private.store_items, private.store_collections,")
    out.append("  private.store_cosmetics, private.store_seasons, private.store_pass_rewards, private.store_level_rewards, private.store_level_cards, private.store_retired,")
    out.append("  private.store_gold_products, private.store_money_packs, private.store_services, private.store_rarity_prices,")
    out.append("  private.store_event_sets, private.store_event_boxes, private.store_event_items;")

    out.append(rows("store_box_kinds", ["kind", "price", "card_pack"],
                    [(b["id"], gold["boxes"][b["id"]], bool(b.get("cardPack"))) for b in boxes]))
    box_rows = []
    for b in boxes:
        for i, r in enumerate(b["rows"], start=1):
            box_rows.append((b["id"], i, r["rarity"], r["prize"], r.get("amount", 0), r["weight"]))
    out.append(rows("store_box_rows", ["kind", "pos", "rarity", "prize", "amount", "weight"], box_rows))
    out.append(rows("store_box_bundles", ["id", "kind", "count", "price"],
                    [(f"{b['kind']}x{b['count']}", b["kind"], b["count"], b["price"]) for b in gold["boxBundles"]]))
    out.append(rows("store_rarity_prices", ["rarity", "price"], [(r, p) for r, p in gold["cosmetics"].items()]))

    col_theme = {c["id"]: c.get("theme", "classic") for c in arts["collections"]}
    bound = set()
    for s in seasons:
        for r in s["rewards"]:
            if r.get("bound"):
                bound.add(r.get("card") or r.get("artifact") or r["id"])
    items = [(a["id"], "artifact", a["rarity"], a["collection"], col_theme.get(a["collection"], "classic"), a["id"] in bound) for a in arts["artifacts"]]
    items += [(c["id"], "profileCard" if c["kind"] == "profile" else "companyCard", c["rarity"], None, c.get("theme", "classic"), c["id"] in bound) for c in cards["cards"]]
    out.append(rows("store_items", ["id", "kind", "rarity", "collection", "theme", "bound"], items))
    out.append(rows("store_level_cards", ["level", "card_id"], [(r["level"], r["card"]) for r in cards["levelRewards"]]))
    out.append(rows("store_collections", ["id", "reward_id", "theme"],
                    [(c["id"], c["reward"], c.get("theme", "classic")) for c in arts["collections"]]))

    cosmetic_rows = []
    seen = set()
    for c in cos["cosmetics"]:
        src = c.get("source", "store")
        price = gold["items"].get(c["id"])
        if price is None and src == "store":
            price = gold["cosmetics"].get(c["rarity"])
        earned = src not in ("box", "collection", "free")
        cosmetic_rows.append((c["id"], c["kind"], c["rarity"], src, price, c.get("theme", "classic"), bool(c.get("bound")) or earned))
        seen.add(c["id"])
    for c in cos["retired"]:
        if c["id"] not in seen:
            cosmetic_rows.append((c["id"], c["kind"], c["rarity"], "retired", None, c.get("theme", "classic"), True))
            seen.add(c["id"])
    event_sets, event_boxes, event_items = [], [], []
    for pos, s in enumerate(events["sets"]):
        event_sets.append((pos, s["id"], s["title"], s["art"]))
        for b in s["boxes"]:
            event_boxes.append((b["id"], s["id"], b["slot"], b["title"]))
            for e in b["items"]:
                event_items.append((e["id"], b["id"], e["rarity"]))
                if e["id"] not in seen:
                    cosmetic_rows.append((e["id"], e["kind"], e["rarity"], "event", None, "classic", False))
                    seen.add(e["id"])
    for a in avatars:
        if a["id"] in seen:
            continue
        price = gold["cosmetics"].get(a.get("tier", "common")) if a.get("unlock") == "gold" else None
        cosmetic_rows.append((a["id"], "avatar", a.get("tier", "common"), "avatar", price, "classic", True))
        seen.add(a["id"])
    for r in retired:
        if r["id"] not in seen:
            cosmetic_rows.append((r["id"], "avatar" if r["id"].startswith("av.") else "retired", "common", "retired", None, "classic", True))
            seen.add(r["id"])
    pass_rows = []
    season_rows = []
    for s in seasons:
        num = s["season"]
        theme = s.get("theme", "classic")
        founder = bool(s.get("founderEdition"))
        season_rows.append((num, theme, founder, (first + timedelta(days=(num - 1) * season_days)).isoformat()))
        for r in s["rewards"]:
            kind = r["kind"]
            rid = r["id"]
            amount = r.get("amount", 0)
            if kind == "card":
                rid = r["card"]
                kind = next(("companyCard" if c["kind"] == "company" else "profileCard") for c in cards["cards"] if c["id"] == rid)
            elif kind == "artifact":
                rid = r["artifact"]
            pass_rows.append((num, "p" if r.get("premium") else "f", r["tier"], rid, kind, amount))
            if kind not in ("box", "gold", "xp", "profileCard", "companyCard", "artifact") and rid not in seen:
                cosmetic_rows.append((rid, kind, r.get("rarity", "common"), "season", None, r.get("theme", theme), bool(r.get("bound"))))
                seen.add(rid)
    out.append(rows("store_cosmetics", ["id", "kind", "rarity", "source", "price", "theme", "bound"], cosmetic_rows))
    out.append(rows("store_event_sets", ["pos", "id", "title", "art"], event_sets))
    out.append(rows("store_event_boxes", ["id", "set_id", "slot", "title"], event_boxes))
    out.append(rows("store_event_items", ["item_id", "box_id", "rarity"], event_items))
    out.append(rows("store_seasons", ["season", "theme", "founder", "starts"], season_rows))
    out.append(rows("store_pass_rewards", ["season", "track", "tier", "reward_id", "kind", "amount"], pass_rows))
    out.append(rows("store_level_rewards", ["level", "gold"], [(r["level"], r["gold"]) for r in levels]))
    out.append(rows("store_retired", ["id", "gold"], [(r["id"], r["gold"]) for r in retired]))

    products = [("com.ledger." + p["id"], "gold", p["gold"], None, 0) for p in real["goldPacks"]]
    for key, pid in (("seasonBundle", "com.ledger.season.bundle"), ("seasonLevels", "com.ledger.season.levels")):
        b = real[key]
        box = b["boxes"][0] if b["boxes"] else {"kind": None, "count": 0}
        products.append((pid, "pass", b["gold"], box["kind"], box["count"]))
    products.append(("com.ledger.pro", "perk", real["bundles"]["pro"]["gold"], None, 0))
    products.append(("com.ledger.pro.yearly", "perk", real["bundles"]["pro"]["gold"], None, 0))
    products.append(("com.ledger.founder", "perk", real["bundles"]["founder"]["gold"], None, 0))
    products.append(("com.ledger.plus.monthly", "plan", 0, None, 0))
    products.append(("com.ledger.plus.yearly", "plan", 0, None, 0))
    out.append(rows("store_gold_products", ["product_id", "kind", "gold", "box_kind", "box_count"], products))

    packs = [(p["id"], p["gold"], p["bonusPercent"], False) for p in gold["moneyPacks"]]
    f = gold["freeMoneyPack"]
    packs.append((f["id"], f["gold"], 0, True))
    out.append(rows("store_money_packs", ["id", "gold", "bonus_percent", "free"], packs))
    out.append(rows("store_services", ["id", "price"], sorted(gold["services"].items())))

    settings = {
        "seasonDays": season_days,
        "freeMoneyPerDay": f["perDay"],
        "founderPassTiers": real["bundles"]["founder"]["passTiers"],
        "founderLastSeason": real["bundles"]["founder"]["lastSeason"],
        "levelsTiers": real["seasonLevels"].get("tiers", 0),
        "moneyPackWeeklyGold": gold["moneyPackWeeklyGold"],
        "eventEpochDay": date.fromisoformat(events["epoch"]).toordinal(),
        "eventRotationDays": events["rotationDays"],
    }
    out.append("create or replace function private.store_setting(k text) returns int language sql immutable as $$")
    out.append("  select (" + q(json.dumps(settings, sort_keys=True)) + "::jsonb ->> k)::int;")
    out.append("$$;")
    out.append("-- store catalog end")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
