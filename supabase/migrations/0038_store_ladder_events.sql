-- Store price ladder, the Elite box, event boxes that rotate every two weeks, prices an administrator can change live,
-- and starter clothes that become mission loot. Every catalogue price stays in the catalogue below; overrides sit on top.

-- The price of a guaranteed item of each rarity (shelf, store items, profile icons).
create table private.store_rarity_prices (rarity text primary key, price int not null check (price > 0));

-- Event boxes: sets in schedule order, six boxes a set, and the exclusive items of each box.
create table private.store_event_sets (pos int primary key, id text not null unique, title text not null, art text not null);
create table private.store_event_boxes (
  id text primary key, set_id text not null, slot int not null check (slot between 1 and 6), title text not null, unique (set_id, slot)
);
create table private.store_event_items (item_id text primary key, box_id text not null, rarity text not null);

-- Prices an administrator set in the store; they win over the catalogue for everyone at once.
create table private.store_price_overrides (
  kind text not null check (kind in ('box', 'bundle', 'item', 'rarity', 'service')),
  id text not null,
  price int not null check (price between 1 and 1000000),
  updated_by uuid,
  updated_at timestamptz not null default now(),
  primary key (kind, id)
);

-- Mission loot: at most one item a server day, each item once.
create table public.mission_drops (
  user_id uuid not null references public.profiles (id) on delete cascade,
  cosmetic_id text not null,
  day int not null,
  created_at timestamptz not null default now(),
  primary key (user_id, cosmetic_id)
);
create index mission_drops_day on public.mission_drops (user_id, day);
alter table public.mission_drops enable row level security;
revoke all on public.mission_drops from anon, authenticated;
revoke all on private.store_rarity_prices, private.store_event_sets, private.store_event_boxes, private.store_event_items,
  private.store_price_overrides from public, anon, authenticated;

