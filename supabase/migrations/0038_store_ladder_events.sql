  select case when k.price > 0 then coalesce(private.override_price('box', k.kind), k.price) else 0 end from private.store_box_kinds k where k.kind = p_kind;
$$;

create or replace function private.bundle_price(p_id text) returns int language sql stable security definer set search_path = '' as $$
  select coalesce(private.override_price('bundle', b.id), b.price) from private.store_box_bundles b where b.id = p_id;
$$;

create or replace function private.rarity_price(p_rarity text) returns int language sql stable security definer set search_path = '' as $$
  select coalesce(private.override_price('rarity', p_rarity), (select r.price from private.store_rarity_prices r where r.rarity = p_rarity));
$$;

create or replace function private.service_price(p_id text) returns int language sql stable security definer set search_path = '' as $$
  select coalesce(private.override_price('service', s.id), s.price) from private.store_services s where s.id = p_id;
$$;

-- What one cosmetic costs for gold: save slots their own price; store items and profile icons the price of their rarity;
-- box items (shelf only) the price of their rarity. An administrator's price for the item wins. Null when not sold.
create or replace function private.cosmetic_price(p_id text) returns int language sql stable security definer set search_path = '' as $$
  select case
           when c.source = 'box' then coalesce(private.override_price('item', c.id), private.rarity_price(c.rarity))
           when c.price is null then null
           when c.kind = 'saveSlot' then coalesce(private.override_price('item', c.id), c.price)
           when c.source in ('store', 'avatar') then coalesce(private.override_price('item', c.id), private.rarity_price(c.rarity), c.price)
         end
    from private.store_cosmetics c where c.id = p_id;
$$;

-- Event rotation: rotation n (0 at the epoch day, a new one every eventRotationDays UTC days) shows set n modulo the set count.
create or replace function private.event_rotation(p_day int default private.era_day()) returns int language sql stable set search_path = '' as $$
  select floor((p_day - private.store_setting('eventEpochDay'))::numeric / private.store_setting('eventRotationDays'))::int;
$$;

create or replace function private.event_set(p_day int default private.era_day()) returns text language sql stable security definer set search_path = '' as $$
  select s.id from private.store_event_sets s
   where s.pos = (((private.event_rotation(p_day) % (select count(*) from private.store_event_sets)::int)
                   + (select count(*) from private.store_event_sets)::int) % (select count(*) from private.store_event_sets)::int);
$$;

create or replace function private.event_box(p_slot int, p_day int default private.era_day()) returns text language sql stable security definer set search_path = '' as $$
  select b.id from private.store_event_boxes b where b.set_id = private.event_set(p_day) and b.slot = p_slot;
$$;

-- The daily shelf now prices by the rarity ladder (and an administrator's prices); legendary items stay box-only and
-- event items never come up (they are not box or store items).
create or replace function private.store_shelf(p_day int) returns table (id text, price int)
language sql stable security definer set search_path = '' as $$
  with priced as (
    select c.id, private.cosmetic_price(c.id) as price
      from private.store_cosmetics c
     where c.source in ('box', 'store') and c.kind not in ('saveSlot', 'tradePlate') and c.rarity <> 'legendary' and private.theme_live(c.theme)
       and not exists (select 1 from private.store_pass_rewards r where r.reward_id = c.id)
  )
  select p.id, p.price from priced p where p.price > 0
   order by md5(p.id || ':' || p_day::text), p.id
   limit private.store_extra('shelfSize');
$$;

-- One box roll with the published odds. An event box's epic and legendary cosmetics come only from the exclusive items of
-- the event box in its slot today; every other cosmetic row uses the usual box pool, which never holds event items.
create or replace function private.roll_box(uid uuid, p_kind text, p_paid boolean, p_pity int, p_claim text) returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare guaranteed boolean := p_paid and p_pity >= 9; total int; pick double precision; acc int := 0; r record; chosen record;
        item record; cos text; doubled boolean; done text[] := '{}'; s int; content jsonb; pool_kind text; ev text;
begin
  select coalesce(sum(weight), 0) into total from private.store_box_rows
   where kind = p_kind and (not guaranteed or (prize not in ('gold', 'money') and private.rarity_rank(rarity) >= 1));
  if total = 0 then raise exception 'unknown_item' using errcode = 'P0001'; end if;
  select * into chosen from private.store_box_rows
   where kind = p_kind and (not guaranteed or (prize not in ('gold', 'money') and private.rarity_rank(rarity) >= 1))
   order by pos desc limit 1;
  pick := random() * total;
  for r in select * from private.store_box_rows
            where kind = p_kind and (not guaranteed or (prize not in ('gold', 'money') and private.rarity_rank(rarity) >= 1)) order by pos loop
    acc := acc + r.weight;
    if pick < acc then chosen := r; exit; end if;
  end loop;

  if chosen.prize = 'gold' then
    doubled := not p_paid and random() < 0.01;
    content := jsonb_build_object('type', 'gold', 'amount', chosen.amount * case when doubled then 2 else 1 end, 'doubled', doubled);
    perform private.store_credit(uid, chosen.amount * case when doubled then 2 else 1 end, 'box_gold', p_claim);
  elsif chosen.prize = 'money' then
    insert into public.money_claims (id, user_id, kind, amount, day) values (p_claim, uid, 'prize', chosen.amount, private.era_day());
    content := jsonb_build_object('type', 'money', 'amount', chosen.amount, 'claimID', p_claim);
  else
    if chosen.prize = 'cosmetic' then
      if p_kind ~ '^event[1-6]$' and private.rarity_rank(chosen.rarity) >= 2 then
        ev := private.event_box(substr(p_kind, 6)::int);
        select i.item_id into cos from private.store_event_items i
         where i.box_id = ev and i.rarity = chosen.rarity
           and not exists (select 1 from public.cosmetic_grants g where g.user_id = uid and g.cosmetic_id = i.item_id)
         order by random() limit 1;
      else
        select c.id into cos from private.store_cosmetics c
         where c.rarity = chosen.rarity and c.kind <> 'saveSlot' and c.source in ('box', 'store') and private.theme_live(c.theme)
           and not exists (select 1 from public.cosmetic_grants g where g.user_id = uid and g.cosmetic_id = c.id)
         order by random() limit 1;
      end if;
      if cos is not null then
        insert into public.cosmetic_grants (user_id, cosmetic_id, source) values (uid, cos, 'box') on conflict do nothing;
        content := jsonb_build_object('type', 'cosmetic', 'id', cos);
      end if;
    end if;
    if content is null then
      pool_kind := case chosen.prize when 'profileCard' then 'profileCard' when 'companyCard' then 'companyCard' else 'artifact' end;
      select i.id, i.rarity into item from private.store_items i
       where i.kind = pool_kind and i.rarity = chosen.rarity and private.theme_live(i.theme) order by random() limit 1;
      if item.id is null then
        select i.id, i.rarity into item from private.store_items i
         where i.kind = 'artifact' and i.rarity = chosen.rarity and private.theme_live(i.theme) order by random() limit 1;
      end if;
      if item.id is null then raise exception 'unknown_item' using errcode = 'P0001'; end if;
      s := private.pick_serial(uid, item.id, item.rarity);
      done := private.cabinet_add(uid, item.id, s, 'found', 'box');
      content := jsonb_build_object('type', 'artifact', 'defID', item.id, 'serial', s);
    end if;
  end if;
  return jsonb_build_object('rarity', chosen.rarity, 'guaranteed', guaranteed, 'content', content, 'completed', to_jsonb(done));
end $$;

-- Opening boxes: stock first, the rest bought at the box's price now (an administrator's price wins).
create or replace function public.open_boxes(p_kind text, p_count int, p_request text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := private.require_player(); prev jsonb; bk private.store_box_kinds; stock int; from_stock int; to_buy int;
        w public.gold_wallets; v_pity int; paid boolean; res jsonb := '[]'::jsonb; one jsonb; done text[] := '{}'; out jsonb;
begin
  perform private.require_free(uid, 'gold');
  prev := private.store_request(uid, p_request, 'open', 30, 500);
  if prev is not null then return prev || jsonb_build_object('state', private.store_state_for(uid)); end if;
  select * into bk from private.store_box_kinds where kind = p_kind;
  if not found then raise exception 'unknown_item' using errcode = 'P0001'; end if;
  if p_count is null or p_count < 1 or p_count > 10 then raise exception 'invalid_amount' using errcode = 'P0001'; end if;
  w := private.wallet(uid);
  paid := bk.price > 0;
  stock := coalesce((select count from public.gold_box_stock where user_id = uid and kind = p_kind), 0);
  from_stock := least(stock, p_count);
  to_buy := p_count - from_stock;
  if to_buy > 0 then
    if not paid then raise exception 'no_box' using errcode = 'P0001'; end if;
    perform private.store_spend(uid, to_buy * private.box_price(p_kind), 'box', p_kind || ':' || p_request);
  end if;
  if from_stock > 0 then update public.gold_box_stock set count = count - from_stock where user_id = uid and kind = p_kind; end if;
  v_pity := w.pity;
  for i in 1..p_count loop
    one := private.roll_box(uid, p_kind, paid, v_pity, p_request || ':' || i);
    if paid then v_pity := case when private.rarity_rank(one ->> 'rarity') >= 1 and (one -> 'content' ->> 'type') not in ('gold', 'money') then 0 else least(100, v_pity + 1) end; end if;
    done := done || array(select jsonb_array_elements_text(one -> 'completed'));
    res := res || jsonb_build_array(one - 'completed');
  end loop;
  update public.gold_wallets set pity = v_pity, boxes_opened = boxes_opened + p_count where user_id = uid;
  out := jsonb_build_object('kind', p_kind, 'results', res, 'completed', to_jsonb(done));
  perform private.store_done(uid, p_request, 'open', out);
  return out || jsonb_build_object('state', private.store_state_for(uid));
end $$;

-- Gold spent on a box bundle, a store cosmetic, a profile icon, a service or a money pack, at today's prices.
create or replace function public.store_buy(p_kind text, p_id text, p_request text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := private.require_player(); prev jsonb; out jsonb; b private.store_box_bundles; v_price int;
        mp private.store_money_packs; used int; cap int := private.store_setting('moneyPackWeeklyGold'); v_today int := private.era_day();
begin
  perform private.require_free(uid, 'gold');
  prev := private.store_request(uid, p_request, 'buy', 20, 300);
  if prev is not null then return prev || jsonb_build_object('state', private.store_state_for(uid)); end if;
  if p_kind = 'bundle' then
    select * into b from private.store_box_bundles where id = p_id;
    if not found then raise exception 'unknown_item' using errcode = 'P0001'; end if;
    perform private.store_spend(uid, private.bundle_price(p_id), 'bundle', p_id);
    perform private.add_boxes(uid, b.kind, b.count);
    out := jsonb_build_object('kind', p_kind, 'id', p_id);
  elsif p_kind = 'cosmetic' then
    if exists (select 1 from private.store_pass_rewards r where r.reward_id = p_id) then raise exception 'unknown_item' using errcode = 'P0001'; end if;
    select private.cosmetic_price(k.id) into v_price from private.store_cosmetics k
     where k.id = p_id and k.source = 'store' and k.kind = 'saveSlot' and k.price is not null and private.theme_live(k.theme);
    if v_price is null then select s.price into v_price from private.store_shelf(v_today) s where s.id = p_id; end if;
    if v_price is null then select s.price into v_price from private.store_shelf(v_today - 1) s where s.id = p_id; end if;
    if v_price is null then raise exception 'unknown_item' using errcode = 'P0001'; end if;
    if exists (select 1 from public.cosmetic_grants where user_id = uid and cosmetic_id = p_id) then raise exception 'already_owned' using errcode = 'P0001'; end if;
    perform private.store_spend(uid, v_price, p_kind, p_id);
    insert into public.cosmetic_grants (user_id, cosmetic_id, source) values (uid, p_id, 'store');
    out := jsonb_build_object('kind', p_kind, 'id', p_id);
  elsif p_kind = 'avatar' then
    select private.cosmetic_price(k.id) into v_price from private.store_cosmetics k
     where k.id = p_id and k.price is not null and private.theme_live(k.theme) and k.source = 'avatar';
    if v_price is null then raise exception 'unknown_item' using errcode = 'P0001'; end if;
    if exists (select 1 from public.cosmetic_grants where user_id = uid and cosmetic_id = p_id) then raise exception 'already_owned' using errcode = 'P0001'; end if;
    perform private.store_spend(uid, v_price, p_kind, p_id);
    insert into public.cosmetic_grants (user_id, cosmetic_id, source) values (uid, p_id, 'store');
    out := jsonb_build_object('kind', p_kind, 'id', p_id);
  elsif p_kind = 'service' then
    v_price := private.service_price(p_id);
    if v_price is null then raise exception 'unknown_item' using errcode = 'P0001'; end if;
    perform private.store_spend(uid, v_price, 'service', p_id);
    out := jsonb_build_object('kind', p_kind, 'id', p_id);
  elsif p_kind = 'money' then
    select * into mp from private.store_money_packs where id = p_id and not free;
    if not found then raise exception 'unknown_item' using errcode = 'P0001'; end if;
    if private.is_admin(uid) then cap := 1000000000; end if;
    used := coalesce((select sum(gold) from public.money_claims where user_id = uid and kind = 'pack' and created_at > now() - interval '7 days'), 0);
    if used + mp.gold > cap then raise exception 'weekly_limit:%', greatest(0, cap - used) using errcode = 'P0001'; end if;
    perform private.store_spend(uid, mp.gold, 'money_pack', p_id);
    insert into public.money_claims (id, user_id, kind, pack_id, gold, day) values (p_request, uid, 'pack', p_id, mp.gold, private.era_day());
    out := jsonb_build_object('kind', p_kind, 'id', p_id, 'claimID', p_request);
  else
    raise exception 'unknown_item' using errcode = 'P0001';
  end if;
  perform private.store_done(uid, p_request, 'buy', out);
  return out || jsonb_build_object('state', private.store_state_for(uid));
end $$;

-- Prices the app shows: every box, bundle, rarity and service, save slots and items an administrator priced.
create or replace function private.store_prices() returns jsonb language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'boxes', coalesce((select jsonb_object_agg(k.kind, private.box_price(k.kind)) from private.store_box_kinds k), '{}'::jsonb),
    'bundles', coalesce((select jsonb_object_agg(b.id, private.bundle_price(b.id)) from private.store_box_bundles b), '{}'::jsonb),
    'rarity', coalesce((select jsonb_object_agg(r.rarity, private.rarity_price(r.rarity)) from private.store_rarity_prices r), '{}'::jsonb),
    'items', coalesce((select jsonb_object_agg(c.id, private.cosmetic_price(c.id)) from private.store_cosmetics c
                         where (c.kind = 'saveSlot' and c.source = 'store')
                            or exists (select 1 from private.store_price_overrides o where o.kind = 'item' and o.id = c.id)), '{}'::jsonb),
    'services', coalesce((select jsonb_object_agg(s.id, private.service_price(s.id)) from private.store_services s), '{}'::jsonb));
$$;

