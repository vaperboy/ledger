-- Accounts that had the old free clothes keep them; new accounts find them as mission loot.
create or replace function private.grant_legacy_free() returns int language plpgsql security definer set search_path = '' as $$
declare n int;
begin
  insert into public.cosmetic_grants (user_id, cosmetic_id, source)
    select p.id, c.id, 'legacy_free' from public.profiles p, private.store_cosmetics c where c.source = 'mission'
    on conflict do nothing;
  get diagnostics n = row_count;
  return n;
end $$;
revoke execute on function private.grant_legacy_free() from public, anon, authenticated;
select private.grant_legacy_free();

