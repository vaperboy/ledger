#!/usr/bin/env python3
"""Writes Engine/Sources/SaveSystem/LegacyIds.swift from the mapping in neutralize_ids.py (one source of truth)."""
import pathlib
here = pathlib.Path(__file__).resolve().parent
ns = {"__file__": str(here / "neutralize_ids.py")}
exec((here / "neutralize_ids.py").read_text().split("def rn")[0], ns)
DOCS = ns["DOCS"]
lines = "\n".join(f'        "{a}": "{b}",' for a, b in sorted(DOCS.items()))
swift = f'''import Foundation
import GameCore

/// Saves from the HTML game use identifiers that were taken from Norwegian words (company forms `ENK` / `AS`, permit ids such as
/// `mva` or `skjenk`). The native game uses neutral English ids. This turns the old ids into the new ones when a save is imported.
/// Generated by `tools/gen_legacy_ids.py` from the mapping in `tools/neutralize_ids.py`, which was also applied to the data files.
public enum LegacyIds {{
    static let documents: [String: String] = [
{lines}
    ]
    static let forms: [String: String] = ["ENK": "soleTrader", "AS": "limited"]
    static let paperwork: [String: String] = ["areg": "authority_report", "hms": "safety_intro"]
    static let stocks: [String: String] = ["NRDK": "ENRG", "FJSF": "FOOD", "HVBK": "BANK", "STVK": "INDU", "TLNR": "TELE", "SKOG": "MATL", "SHIP": "TRAN", "EIEN": "PROP"]
    static let crypto: [String: String] = ["NRC": "ALT"]

    private static func renameKeys(_ v: JSONValue, _ map: [String: String]) -> JSONValue {{
        guard !v.isNull else {{ return v }}
        var o: [String: JSONValue] = [:]
        for (k, x) in v.object {{ o[map[k] ?? k] = x }}
        return .object(o)
    }}

    /// Rename ids inside a legacy save, in place. Safe to run twice.
    public static func migrate(_ root: inout [String: JSONValue]) {{
        var companies = root["cos"]?.array ?? []
        for i in companies.indices {{
            if !companies[i]["form"].isNull, let n = forms[companies[i]["form"].string] {{ companies[i]["form"] = .string(n) }}
            let docs = companies[i]["docs"]
            if !docs.isNull {{
                var renamed: [String: JSONValue] = [:]
                for (k, v) in docs.object {{ renamed[documents[k] ?? k] = v }}
                companies[i]["docs"] = .object(renamed)
            }}
            var staff = companies[i]["staff"].array
            for k in staff.indices where !staff[k]["onb"].isNull {{
                var o: [String: JSONValue] = [:]
                for (key, v) in staff[k]["onb"].object {{ o[paperwork[key] ?? key] = v }}
                staff[k]["onb"] = .object(o)
            }}
            if !staff.isEmpty {{ companies[i]["staff"] = .array(staff) }}
        }}
        if !companies.isEmpty {{ root["cos"] = .array(companies) }}
        // Listed companies and coins got neutral tickers (the old ones were Norwegian words).
        if let s = root["stocks"] {{ root["stocks"] = renameKeys(s, stocks) }}
        if let c = root["crypto"] {{ root["crypto"] = renameKeys(c, crypto) }}
        if var inv = root["inv"], !inv.isNull {{
            if !inv["stocks"].isNull {{ inv["stocks"] = renameKeys(inv["stocks"], stocks) }}
            if !inv["crypto"].isNull {{ inv["crypto"] = renameKeys(inv["crypto"], crypto) }}
            root["inv"] = inv
        }}
    }}
}}
'''
(here.parent / "Engine/Sources/SaveSystem/LegacyIds.swift").write_text(swift)
print("written", len(DOCS))
